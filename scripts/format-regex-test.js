import assert from 'node:assert/strict';
import * as h from '../packages/js/src/index.js';
assert.equal(h.formatDuration(3661001), '01:01:01');
assert.equal(h.formatFileSize(1048576),'1 MiB');
assert.equal(h.formatPhoneVN('0901234567'),'0901 234 567');
assert.equal(h.padNumber(-4,3),'-004');
assert.equal(h.formatOrdinal(23),'23rd');
assert.equal(h.formatPercent(.125,{locale:'en-US',digits:1}),'12.5%');
assert.equal(h.formatList(['a','b'],{locale:'en-US'}),'a and b');
assert.match(h.formatCompactNumber(1200),/1\.2K/);
assert.equal(h.escapeRegExp('[x]'),'\\[x\\]');
assert.equal(h.isMatch('ABC','abc','i'),true);
assert.deepEqual(h.extractMatches('a1b2',/\d/).map(x=>x.match),['1','2']);
assert.equal(h.getFirstMatch('a2',/\d/).match,'2');
assert.equal(h.replaceAllRegex('a1b2',/\d/,'#'),'a#b#');
assert.equal(h.normalizeWhitespace(' a\t b '),'a b');
assert.equal(h.extractEmails('abc@test.vn')[0],'abc@test.vn');
assert.equal(h.maskByPattern('0901234567',/^(\d{3})\d{4}(\d{3})$/),'090****567');
assert.equal(h.validatePattern('[').valid,false);
console.log('Format + Regex: 17 offline assertions passed.');
