import assert from 'node:assert/strict';
import { withTimeout, promisePool, httpClient, AppError, tryCatch, joinUrl, retry, buildQueryString, parseQueryString } from '../packages/js/src/index.js';
assert.equal(await withTimeout(Promise.resolve(7), 30),7);
await assert.rejects(withTimeout(new Promise(()=>{}),3), e=>e.name==='TimeoutError');
const ac=new AbortController();ac.abort();await assert.rejects(withTimeout(Promise.resolve(1),100,{signal:ac.signal}),e=>e.name==='AbortError');
let active=0, max=0;
assert.deepEqual(await promisePool([1,2,3,4],async n=>{active++;max=Math.max(max,active);await new Promise(r=>setTimeout(r,2));active--;return n*2;},2),[2,4,6,8]);assert.ok(max<=2);
const [e,v]=await tryCatch(async()=>4);assert.equal(e,null);assert.equal(v,4);
assert.ok((await tryCatch(()=>{throw Error('x')}))[0]);
assert.equal(new AppError('Oops',{status:403}).toJSON().status,403);
assert.equal(joinUrl('https://example.com/api/','/users','/42'),'https://example.com/api/users/42');
assert.deepEqual(parseQueryString(buildQueryString({q:'x',a:[1,2]})),{q:'x',a:['1','2']});
let count=0;
const client=httpClient({baseUrl:'https://example.com/api/',retries:2,timeoutMs:50,fetchImpl:async(url,init)=>{count++;assert.ok(init.signal);return {ok:count>=2,status:count>=2?200:503,json:async()=>({ok:true,url})};}});
assert.equal((await client('items')).ok,true);assert.equal(count,2);
count=0;
const failing=httpClient({retries:5,fetchImpl:async()=>{count++;return {ok:false,status:503};}});
await assert.rejects(failing('https://example.com',{method:'POST'}),e=>e.status===503);assert.equal(count,1);
const timeoutClient=httpClient({timeoutMs:5,fetchImpl:(_url,{signal})=>new Promise((resolve,reject)=>signal.addEventListener('abort',()=>reject(new DOMException('Aborted','AbortError')),{once:true}))});
await assert.rejects(timeoutClient('https://example.com'),e=>e.code==='TIMEOUT');
await assert.rejects(retry(()=>Promise.reject(Error('no')),{attempts:2,delayMs:1}),/no/);
