import assert from 'node:assert/strict';
import { hashSha256, hmacSha256, generateSecureToken, base64UrlEncode, base64UrlDecode, constantTimeEqual, parseJwtPayload, sanitizeFilename, redactSensitiveData, bytesToHex, hexToBytes } from '../packages/js/src/index.js';
assert.equal(await hashSha256('abc'),'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
assert.equal(await hmacSha256('The quick brown fox jumps over the lazy dog','key'),'f7bc83f430538424b13298e6aa6fb143ef4d59a14946175997479dbc2d1a3cd8');
assert.match(generateSecureToken(16), /^[0-9a-f]{32}$/);
assert.notEqual(generateSecureToken(16),generateSecureToken(16));
assert.throws(()=>generateSecureToken(0),RangeError);
for (const text of ['', 'Xin chào Việt Nam 🇻🇳', 'hello']) assert.equal(base64UrlDecode(base64UrlEncode(text)),text);
assert.throws(()=>base64UrlDecode('A'),TypeError);
assert.throws(()=>base64UrlDecode('////'),TypeError);
assert.equal(constantTimeEqual(new Uint8Array([1,2]),new Uint8Array([1,2])),true);
assert.equal(constantTimeEqual(new Uint8Array([1,2]),new Uint8Array([1,2,0])),false);
assert.equal(parseJwtPayload(`e30.${base64UrlEncode('{"sub":"123"}')}.abc`).sub,'123');
assert.throws(()=>parseJwtPayload('not-a-jwt'),TypeError);
assert.ok(!sanitizeFilename('../CON.txt').includes('/'));
assert.equal(sanitizeFilename('CON.txt'),'_CON.txt');
const data={ password:'topsecret', nested:{api_key:'secret', safe:'yes'}};data.self=data;
const cleaned=redactSensitiveData(data);
assert.equal(cleaned.password,'[REDACTED]');assert.equal(cleaned.nested.api_key,'[REDACTED]');assert.equal(cleaned.nested.safe,'yes');assert.equal(cleaned.self,cleaned);assert.equal(data.password,'topsecret');
assert.equal(bytesToHex(hexToBytes('Ff00aB')),'ff00ab');
assert.throws(()=>hexToBytes('zz'),TypeError);
console.log('Security v0.6.0 behavioral tests PASS');
