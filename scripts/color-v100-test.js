import assert from 'node:assert/strict';
import {hexToRgb,rgbToHex,hexToHsl,hslToHex,normalizeColor,isValidColor,getLuminance,contrastRatio,meetsWcagContrast,getReadableTextColor,mixColors,lightenColor,darkenColor,complementaryColor,generateColorPalette} from '../packages/js/src/index.js';
assert.deepEqual(hexToRgb('#abc'),{r:170,g:187,b:204,a:1});
assert.equal(rgbToHex(255,0,128),'#ff0080');
assert.deepEqual(hexToHsl('#ff0000'),{h:0,s:100,l:50});
assert.equal(hslToHex(240,100,50),'#0000ff');
assert.equal(normalizeColor('rgba(255,0,0,0.5)'),'#ff000080');
assert.equal(isValidColor('red'),false);
assert.equal(getLuminance('#000'),0);
assert.ok(Math.abs(contrastRatio('#000','#fff')-21)<1e-8);
assert.equal(meetsWcagContrast('#000','#fff','AAA'),true);
assert.equal(getReadableTextColor('#000'),'#ffffff');
assert.equal(mixColors('#000','#fff'),'#808080');
assert.equal(lightenColor('#000',1),'#ffffff');
assert.equal(darkenColor('#fff',1),'#000000');
assert.equal(complementaryColor('#f00'),'#00ffff');
assert.equal(generateColorPalette('#369',5).length,5);
assert.throws(()=>hexToRgb('#qqqqqq'));
assert.throws(()=>contrastRatio('#000','#fff8'));
console.log('Color v1.0.0 offline tests: PASS (17 assertions)');
