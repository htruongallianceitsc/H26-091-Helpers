import assert from 'node:assert/strict';
import {get,set,isEmpty,isEqual,flattenObject,unflattenObject,diffObjects,normalizeApiResponse,sortBy,keyBy,paginate,difference,intersection,sumBy,average} from '../packages/js/src/index.js';
assert.equal(get({a:[{b:3}]},'a.0.b'),3);
assert.equal(get({},'none','fallback'),'fallback');
const original={a:{b:1}};assert.equal(set(original,'a.b',9).a.b,9);assert.equal(original.a.b,1);
assert.throws(()=>set({},'__proto__.polluted',1));
assert.equal(isEmpty({}),true);assert.equal(isEmpty(new Set([1])),false);
assert.equal(isEqual({a:[1,2]},{a:[1,2]}),true);assert.equal(isEqual({a:1},{a:2}),false);
const c1={x:1};c1.self=c1;const c2={x:1};c2.self=c2;assert.equal(isEqual(c1,c2),true);
const flat=flattenObject({a:{b:1},c:[]});assert.equal(flat['a.b'],1);
assert.deepEqual(unflattenObject(flat),{a:{b:1},c:[]});
assert.throws(()=>unflattenObject({'__proto__.danger':1}));
assert.equal(diffObjects({a:1,b:1},{a:2,c:3}).length,3);
assert.deepEqual(normalizeApiResponse({success:false,error:'bad'}),{success:false,data:null,error:'bad'});
assert.deepEqual(sortBy([{a:2},{a:1}],x=>x.a).map(x=>x.a),[1,2]);
assert.equal(keyBy([{id:'x',n:1},{id:'x',n:2}],x=>x.id).get('x').n,2);
assert.deepEqual(paginate([1,2,3,4,5],2,2).items,[3,4]);
assert.deepEqual(difference([1,2,2,3],[2]),[1,3]);
assert.deepEqual(intersection([1,2,2,3],[2,3]),[2,3]);
assert.equal(sumBy([{n:2},{n:3}],x=>x.n),5);assert.equal(average([],x=>x),null);
assert.equal(average([2,4]),3);
console.log('Data transformation v0.7.0 behavioral tests PASS');
